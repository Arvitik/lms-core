$(".checkName").change(function() {
    var field = $(this);
    var value = field.val();
    var nameType = field.attr('name'); // first_name ??? last_name
    $.ajax({
        cache: false,
        type: 'POST',
        url: '/check/nameValid', // ??????? ???? ??????? ? Laravel
        beforeSend: function(xhr) {
            var token = $('meta[name="csrf_token"]').attr('content');
            if (token) {
                return xhr.setRequestHeader('X-CSRF-TOKEN', token);
            }
        },
        data: { name: value, type: nameType },
        success: function(data) {
            if (data == "invalid") {
                if (nameType == "first_name") {
                    $('#firstNameError').show().text("??? ?????? ?????????? ? ????????? ?????, ??? ????? 3 ?????????? ???????? ??????.");
                } else {
                    $('#lastNameError').show().text("??????? ?????? ?????????? ? ????????? ?????, ??? ????? 3 ?????????? ???????? ??????.");
                }
                $(':input[type="submit"]').prop('disabled', true);
            } else {
                if (nameType == "first_name") {
                    $('#firstNameError').hide();
                } else {
                    $('#lastNameError').hide();
                }

                // ???????????? ?????? ?????? ???? ??? ???? ???????
                var firstValid = $('#first_name').val() && !$('#firstNameError').is(':visible');
                var lastValid  = $('#last_name').val() && !$('#lastNameError').is(':visible');
                $('#registerSubmit').prop('disabled', !(firstValid && lastValid));
            }
        }
    });
    return false;
});
